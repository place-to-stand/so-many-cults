/**
 * Generate tiny base64 "blur-up" placeholders for every raster image under
 * public/artwork, public/photos and public/posters (thumbnails included) and
 * write them to data/blur-placeholders.json, keyed by public URL path.
 *
 * `next/image` shows the placeholder (scaled + CSS-blurred) while the real
 * file streams in, so the layout is painted with the image's colours instead
 * of a flat block. Each entry is a 16px-wide JPEG, roughly 300–600 bytes.
 *
 * Usage:
 *   npm run blur
 *
 * Run it whenever you add, replace or remove images (the thumbnails script
 * reminds you). The JSON is committed so the build doesn't depend on sharp.
 * sharp ships with Next, so no extra install is needed.
 */
import sharp from 'sharp';
import { readdir, writeFile, stat } from 'fs/promises';
import { join, relative, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const PUBLIC_DIR = join(ROOT, 'public');
const OUT_FILE = join(ROOT, 'data', 'blur-placeholders.json');

/** Folders (under /public) whose images get placeholders. */
const IMAGE_DIRS = ['artwork', 'photos', 'posters'];
const IMAGE_RE = /\.(jpe?g|png|webp|avif)$/i;
/** Width of the placeholder in pixels; height follows the aspect ratio. */
const PLACEHOLDER_WIDTH = 16;

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(full)));
    else if (IMAGE_RE.test(entry.name)) out.push(full);
  }
  return out;
}

async function placeholderFor(file) {
  const buf = await sharp(file)
    .rotate() // honour EXIF orientation so the blur matches what the browser shows
    .resize(PLACEHOLDER_WIDTH, undefined, { fit: 'inside', withoutEnlargement: true })
    .jpeg({ quality: 50, mozjpeg: true })
    .toBuffer();
  return `data:image/jpeg;base64,${buf.toString('base64')}`;
}

async function run() {
  const files = [];
  for (const dir of IMAGE_DIRS) {
    const full = join(PUBLIC_DIR, dir);
    try {
      if ((await stat(full)).isDirectory()) files.push(...(await walk(full)));
    } catch {
      // folder doesn't exist yet — fine
    }
  }
  files.sort();

  const map = {};
  for (const file of files) {
    const url = '/' + relative(PUBLIC_DIR, file).split('\\').join('/');
    map[url] = await placeholderFor(file);
  }

  const json = JSON.stringify(
    {
      _note:
        'Generated by `npm run blur` — do not edit by hand. Base64 blur-up placeholders for next/image, keyed by public URL path. Re-run after adding or replacing images under public/artwork, public/photos or public/posters.',
      ...map,
    },
    null,
    2,
  );
  await writeFile(OUT_FILE, json + '\n');

  const bytes = Buffer.byteLength(json);
  console.log(`✓ ${files.length} placeholders → ${relative(ROOT, OUT_FILE)} (${(bytes / 1024).toFixed(1)} KB)`);
}

run().catch((err) => {
  console.error(err);
  process.exit(1);
});
